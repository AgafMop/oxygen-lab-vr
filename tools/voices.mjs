// Generate Hebrew voice lines with ElevenLabs (eleven_v3), post-process with ffmpeg, QA with Scribe.
// Usage: node tools/voices.mjs [--force id,id] [--only id,id]
// Writes assets/voice/<id>.mp3 and src/game/voices.js. Keys come from the speech-generator skill .env (never printed).
import { readFileSync, writeFileSync, existsSync, mkdirSync, unlinkSync } from 'node:fs';
import { homedir } from 'node:os';
import { execFileSync } from 'node:child_process';
import { LINES } from '../src/game/script.js';

const env = readFileSync(`${homedir()}/.claude/skills/speech-generator/scripts/.env`, 'utf8');
const KEYS = [...env.matchAll(/^ELEVENLABS_API_KEY=(.+)$/gm)].map(m => m[1].trim());
const VOICE = { commander: 'pNInz6obpgDQGcFmaJgB', azoulay: 'EXAVITQu4vr4xnSDxMaL', robi: 'IKne3meq5aSn9XLyUdCD' };
const TAG = { commander: '[serious, commanding]', azoulay: '[confident]', robi: '[cheerful]' };
const FILTER = {
  robi: 'aecho=0.8:0.6:9:0.22,highpass=f=110,acompressor=threshold=-18dB:ratio=3,volume=1.15',
  commander: 'highpass=f=280,lowpass=f=3600,acompressor=threshold=-20dB:ratio=4,volume=1.3',
  azoulay: 'highpass=f=80,acompressor=threshold=-20dB:ratio=2.5,volume=1.1',
};
const OUT = 'assets/voice';
const arg = k => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1].split(',') : null; };
const force = new Set(arg('--force') || []), only = arg('--only');
let keyIdx = 0;

async function tts(text, voice) {
  for (let attempt = 0; attempt < KEYS.length * 2; attempt++) {
    const r = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${voice}?output_format=mp3_44100_128`, {
      method: 'POST', headers: { 'xi-api-key': KEYS[keyIdx], 'Content-Type': 'application/json' },
      body: JSON.stringify({ text, model_id: 'eleven_v3', language_code: 'he' }) });
    if (r.ok) return Buffer.from(await r.arrayBuffer());
    const msg = await r.text();
    if (r.status === 401 || r.status === 402 || r.status === 429 || /quota|credits/i.test(msg)) { keyIdx = (keyIdx + 1) % KEYS.length; continue; }
    throw new Error(`tts ${r.status} ${msg.slice(0, 200)}`);
  }
  throw new Error('all accounts exhausted');
}

async function transcribe(file) {
  const fd = new FormData();
  fd.append('model_id', 'scribe_v1'); fd.append('language_code', 'heb');
  fd.append('file', new Blob([readFileSync(file)], { type: 'audio/mpeg' }), 'a.mp3');
  const r = await fetch('https://api.elevenlabs.io/v1/speech-to-text', { method: 'POST', headers: { 'xi-api-key': KEYS[keyIdx] }, body: fd });
  if (!r.ok) return null;
  return (await r.json()).text || '';
}

const norm = s => s.replace(/[^א-ת0-9]/g, '');
function similarity(a, b) {
  a = norm(a); b = norm(b);
  const d = Array.from({ length: a.length + 1 }, (_, i) => [i, ...Array(b.length).fill(0)]);
  for (let j = 1; j <= b.length; j++) d[0][j] = j;
  for (let i = 1; i <= a.length; i++) for (let j = 1; j <= b.length; j++) d[i][j] = Math.min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
  return 1 - d[a.length][b.length] / Math.max(1, a.length, b.length);
}

async function make(id, l) {
  const raw = `${OUT}/${id}.raw.mp3`, out = `${OUT}/${id}.mp3`;
  writeFileSync(raw, await tts(`${TAG[l.speaker]} ${l.text}`, VOICE[l.speaker]));
  execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', raw, '-af', FILTER[l.speaker], '-ac', '1', '-b:a', '64k', out]);
  unlinkSync(raw);
  return out;
}

mkdirSync(OUT, { recursive: true });
const report = [];
for (const [id, l] of Object.entries(LINES)) {
  if (only && !only.includes(id)) continue;
  const out = `${OUT}/${id}.mp3`;
  if (existsSync(out) && !force.has(id)) continue;
  try {
    await make(id, l);
    let heard = await transcribe(out), sim = heard == null ? null : similarity(l.text, heard);
    if (sim != null && sim < 0.6) { await make(id, l); heard = await transcribe(out); sim = heard == null ? null : similarity(l.text, heard); }
    report.push({ id, sim: sim == null ? 'n/a' : sim.toFixed(2), heard });
    console.log(`${id}  sim=${sim == null ? 'n/a' : sim.toFixed(2)}`);
  } catch (e) { console.error(`FAIL ${id}: ${e.message}`); }
}
const have = Object.keys(LINES).filter(id => existsSync(`${OUT}/${id}.mp3`));
writeFileSync('src/game/voices.js', `// generated by tools/voices.mjs — ids with an mp3 in assets/voice/\nexport const VOICE_AVAILABLE = new Set(${JSON.stringify(have)});\n`);
writeFileSync('.superpowers/voice-report.json', JSON.stringify(report, null, 1));
console.log(`voices: ${have.length}/${Object.keys(LINES).length}`);
